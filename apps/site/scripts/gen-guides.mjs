/**
 * Per-client guide data generator (S15.5).
 *
 * The `/guides/<client>` setup guides must never hand-duplicate config truth — the on-disk config
 * path (per OS), secret strategy, restart requirement, and remote capability all come straight from
 * the real adapter facts in `@mcpfold/adapters`. This Node-only script reads `ALL_ADAPTERS` from the
 * built package and emits a committed, browser-safe plain-data module (`src/guides/guides.data.ts`)
 * that the site imports. Because `ALL_ADAPTERS` transitively pulls `node:os`/`node:path`, importing
 * it directly into browser-bundled code (meta.ts/jsonld.ts) is impossible — so the facts are frozen
 * into plain data here and a CI drift check (`guides:check`) guarantees they stay current.
 *
 * Regenerate:  pnpm --filter @mcpfold/site guides:gen   (after `pnpm -r build`)
 */
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const adaptersEntry = join(here, '..', '..', '..', 'packages', 'adapters', 'dist', 'index.js');
if (!existsSync(adaptersEntry)) {
  console.error('✗ packages/adapters/dist not found — run `pnpm -r build` first.');
  process.exit(1);
}
const { ALL_ADAPTERS } = await import(pathToFileURL(adaptersEntry).href);

/**
 * Human-facing copy that is NOT derivable from the adapter interface: the display name, the config
 * root key each client uses, and (optional) a one-line "where it lives" note. Kept keyed by client id
 * and mirrors docs/coverage.md — the config *truth* (paths/strategy/restart/remote) is still read
 * live from the adapter below, never from this map.
 */
const CLIENT_META = {
  'claude-code': { label: 'Claude Code', configRoot: 'mcpServers' },
  'claude-desktop': { label: 'Claude Desktop', configRoot: 'mcpServers' },
  cursor: { label: 'Cursor', configRoot: 'mcpServers' },
  vscode: { label: 'VS Code', configRoot: 'servers' },
  windsurf: { label: 'Windsurf', configRoot: 'mcpServers' },
  zed: { label: 'Zed', configRoot: 'context_servers' },
  cline: { label: 'Cline', configRoot: 'mcpServers' },
  'gemini-cli': { label: 'Gemini CLI', configRoot: 'mcpServers' },
  jetbrains: { label: 'JetBrains', configRoot: 'mcpServers' },
  'visual-studio': { label: 'Visual Studio', configRoot: 'servers' },
  continue: { label: 'Continue', configRoot: 'mcpServers' },
  'roo-code': { label: 'Roo Code', configRoot: 'mcpServers' },
  goose: { label: 'Goose', configRoot: 'extensions' },
  'codex-cli': { label: 'Codex CLI', configRoot: 'mcp_servers' },
  'lm-studio': { label: 'LM Studio', configRoot: 'mcpServers' },
  warp: { label: 'Warp', configRoot: 'mcpServers' },
  opencode: { label: 'opencode', configRoot: 'mcp' },
  'copilot-cli': { label: 'Copilot CLI', configRoot: 'mcpServers' },
};

// Synthetic per-OS contexts (empty env → the documented fallbacks in paths.ts userConfigDir), so the
// example paths a guide shows are deterministic and independent of the machine running the build.
const OS_CONTEXTS = {
  macos: { platform: 'darwin', home: '/Users/you', env: {} },
  windows: { platform: 'win32', home: 'C:\\Users\\you', env: {} },
  linux: { platform: 'linux', home: '/home/you', env: {} },
};

/** Resolve a client's user-scope config path on an OS, tolerating adapters that don't support it. */
function pathOn(adapter, ctx) {
  try {
    return adapter.resolvePath('user', undefined, ctx);
  } catch {
    return null;
  }
}

const clients = ALL_ADAPTERS.map((adapter) => {
  const meta = CLIENT_META[adapter.id];
  if (!meta) {
    console.error(`✗ no CLIENT_META entry for adapter "${adapter.id}" — add its label/configRoot.`);
    process.exit(1);
  }
  return {
    id: adapter.id,
    label: meta.label,
    configRoot: meta.configRoot,
    secretStrategy: adapter.secretStrategy,
    needsRestart: adapter.needsRestart,
    remote: {
      nativeHttp: adapter.remote.nativeHttp,
      nativeOauth: adapter.remote.nativeOauth,
      fieldShape: adapter.remote.fieldShape,
    },
    paths: {
      macos: pathOn(adapter, OS_CONTEXTS.macos),
      windows: pathOn(adapter, OS_CONTEXTS.windows),
      linux: pathOn(adapter, OS_CONTEXTS.linux),
    },
  };
});

const banner = `// GENERATED by apps/site/scripts/gen-guides.mjs from @mcpfold/adapters — DO NOT EDIT BY HAND.
// The config path (per OS), secret strategy, restart requirement, and remote capability are read
// live from the real adapters so a guide can never drift from what \`mcpfold sync\` actually writes.
// Regenerate with: pnpm --filter @mcpfold/site guides:gen  (drift-checked in CI via guides:check).
`;

const body = `${banner}
/** Secret-handling strategy a client uses (mirrors @mcpfold/adapters SecretStrategy). */
export type GuideSecretStrategy = 'inline' | 'native-input' | 'shim';

/** How a client names its remote-endpoint field, or 'shim' when it has no native remote support. */
export type GuideRemoteFieldShape = 'url' | 'type+url' | 'httpUrl' | 'shim';

/** Everything a per-client setup guide needs, frozen from adapter facts at build time. */
export interface GuideClient {
  readonly id: string;
  readonly label: string;
  /** The top-level key the client stores MCP servers under (e.g. \`mcpServers\`). */
  readonly configRoot: string;
  readonly secretStrategy: GuideSecretStrategy;
  readonly needsRestart: boolean;
  readonly remote: {
    readonly nativeHttp: boolean;
    readonly nativeOauth: boolean;
    readonly fieldShape: GuideRemoteFieldShape;
  };
  /** Example user-scope config path per OS (\`null\` if the client has no user-scope file). */
  readonly paths: {
    readonly macos: string | null;
    readonly windows: string | null;
    readonly linux: string | null;
  };
}

/** Every client mcpfold can fold config out to, in the canonical adapter order. */
export const GUIDE_CLIENTS: readonly GuideClient[] = ${JSON.stringify(clients, null, 2)};

/** Look up a guide by client id. */
export function guideById(id: string): GuideClient | undefined {
  return GUIDE_CLIENTS.find((c) => c.id === id);
}
`;

const outDir = join(here, '..', 'src', 'guides');
mkdirSync(outDir, { recursive: true });
const outFile = join(outDir, 'guides.data.ts');
const existing = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
if (existing === body) {
  console.log(`✓ guides.data.ts already up to date (${clients.length} clients)`);
} else {
  writeFileSync(outFile, body);
  console.log(`✓ wrote guides.data.ts (${clients.length} clients)`);
}
